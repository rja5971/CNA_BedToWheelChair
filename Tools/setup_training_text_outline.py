"""Create a project-owned outline material for world-space hint text."""
import unreal
path='/Game/PatientSetup/Guidance/M_TrainingTextOutline'
m=unreal.load_asset(path)
if m is None:
    m=unreal.AssetToolsHelpers.get_asset_tools().create_asset('M_TrainingTextOutline','/Game/PatientSetup/Guidance',unreal.Material,unreal.MaterialFactoryNew())
    m.set_editor_property('blend_mode',unreal.BlendMode.BLEND_MASKED)
    m.set_editor_property('shading_model',unreal.MaterialShadingModel.MSM_UNLIT)
    m.set_editor_property('two_sided',True)
    def node(cls,x,y):return unreal.MaterialEditingLibrary.create_material_expression(m,cls,x,y)
    def wire(a,out,b,pin):
        assert unreal.MaterialEditingLibrary.connect_material_expressions(a,out,b,pin),(out,pin)
    font=node(unreal.MaterialExpressionFontSampleParameter,-700,100)
    font.set_editor_property('parameter_name','Font')
    font.set_editor_property('font',unreal.load_asset('/Engine/EngineFonts/RobotoDistanceField'))
    vertex=node(unreal.MaterialExpressionVertexColor,-300,-180)
    fill=node(unreal.MaterialExpressionLinearInterpolate,-480,100)
    fill.set_editor_property('const_a',-90.0);fill.set_editor_property('const_b',90.0)
    wire(font,'R',fill,'Alpha')
    mask=node(unreal.MaterialExpressionLinearInterpolate,-480,300)
    mask.set_editor_property('const_a',-85.5);mask.set_editor_property('const_b',94.5)
    wire(font,'R',mask,'Alpha')
    solid=node(unreal.MaterialExpressionSaturate,-240,100);wire(fill,'',solid,'')
    outline=node(unreal.MaterialExpressionVectorParameter,-300,-340)
    outline.set_editor_property('parameter_name','OutlineColor')
    outline.set_editor_property('default_value',unreal.LinearColor(.01,.04,.04,1.0))
    color=node(unreal.MaterialExpressionLinearInterpolate,0,0)
    wire(outline,'',color,'A');wire(vertex,'',color,'B');wire(solid,'',color,'Alpha')
    assert unreal.MaterialEditingLibrary.connect_material_property(color,'',unreal.MaterialProperty.MP_EMISSIVE_COLOR)
    assert unreal.MaterialEditingLibrary.connect_material_property(mask,'',unreal.MaterialProperty.MP_OPACITY_MASK)
    unreal.MaterialEditingLibrary.recompile_material(m)
    unreal.EditorAssetLibrary.save_loaded_asset(m)
unreal.log('TRAINING_TEXT_OUTLINE '+m.get_path_name())
